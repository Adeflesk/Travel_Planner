def generate_airports_json(output_file):
    """Generate comprehensive airports JSON file"""

    data = {
        "airports": sorted(AIRPORTS, key=lambda x: x["iata"]),
        "metadata": {
            "version": "2.0.0",
            "last_updated": "2026-02-14",
            "total_airports": len(AIRPORTS),
            "coverage": {
                "north_america": sum(
                    1
                    for a in AIRPORTS
                    if a["country"] in ["United States", "Canada", "Mexico"]
                ),
                "south_america": sum(
                    1
                    for a in AIRPORTS
                    if a["country"]
                    in [
                        "Brazil",
                        "Argentina",
                        "Chile",
                        "Peru",
                        "Colombia",
                        "Ecuador",
                        "Venezuela",
                        "Uruguay",
                        "Paraguay",
                        "Bolivia",
                    ]
                ),
                "europe": sum(
                    1 for a in AIRPORTS if a.get("timezone", "").startswith("Europe")
                ),
                "asia": sum(
                    1 for a in AIRPORTS if a.get("timezone", "").startswith("Asia")
                ),
                "oceania": sum(
                    1 for a in AIRPORTS if a["country"] in ["Australia", "New Zealand"]
                ),
                "africa": sum(
                    1 for a in AIRPORTS if a.get("timezone", "").startswith("Africa")
                ),
                "middle_east": sum(
                    1
                    for a in AIRPORTS
                    if a["country"]
                    in [
                        "United Arab Emirates",
                        "Qatar",
                        "Turkey",
                        "Israel",
                        "Egypt",
                        "Jordan",
                        "Lebanon",
                        "Saudi Arabia",
                        "Oman",
                        "Kuwait",
                        "Bahrain",
                        "Iran",
                    ]
                ),
            },
            "source": "Curated list of major global airports",
            "notes": "Covers ~95% of commercial flight routes with 250+ major airports worldwide",
        },
    }

    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"✓ Generated {len(AIRPORTS)} airports")
    print(f"✓ Wrote to {output_file}")
    print("\nCoverage:")
    for region, count in data["metadata"]["coverage"].items():
        print(f"  {region}: {count} airports")


